'use strict';
const ALLOWED_PERMISSIONS = new Set(['notifications', 'fullscreen', 'clipboard-sanitized-write']);
const VIDEO_FRAMES = new Set(['www.youtube-nocookie.com', 'www.youtube.com', 'player.vimeo.com']);
function isAppUrl(value, port, documentOnly = true) {
  if (!Number.isInteger(port) || port < 1 || port > 65535) return false;
  try {
    const u = new URL(value);
    return u.protocol === 'http:' && !u.username && !u.password &&
      ['localhost', '127.0.0.1'].includes(u.hostname) && Number(u.port || 80) === port &&
      (!documentOnly || ['/', '/index.html'].includes(u.pathname));
  } catch (_) { return false; }
}
function trustedIpc(event, win, port) {
  try {
    return !!win && !win.isDestroyed() && event.sender === win.webContents &&
      event.senderFrame === win.webContents.mainFrame && isAppUrl(event.senderFrame.url, port);
  } catch (_) { return false; }
}
function allowPermission(wc, permission, details, win, port) {
  try {
    if (!win || win.isDestroyed() || !wc || wc !== win.webContents || !ALLOWED_PERMISSIONS.has(permission)) return false;
    if (details.isMainFrame === true) return isAppUrl(details.requestingUrl, port);
    // These are the two remote lecture players generated by the existing app.
    // Their fullscreen permission does not grant clipboard or device access.
    const u = new URL(details.requestingUrl);
    return permission === 'fullscreen' && details.isMainFrame === false &&
      u.protocol === 'https:' && !u.username && !u.password && VIDEO_FRAMES.has(u.hostname);
  } catch (_) { return false; }
}
function validHost(host, port) {
  return typeof host === 'string' && [`localhost:${port}`, `127.0.0.1:${port}`].includes(host.toLowerCase());
}
module.exports = { isAppUrl, trustedIpc, allowPermission, validHost };
